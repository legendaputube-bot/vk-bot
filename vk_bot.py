def ask_groq(
    user_id: int,
    user_message: str
) -> str:

    user_data = get_user_data(
        user_id
    )

    user_name = user_data.get(
        "name",
        "Участник"
    )

    history = user_data.get(
        "history",
        []
    )

    # =========================
    # ПЕРСОНАЛЬНЫЙ КОНТЕКСТ
    # =========================

    personal_context = f"""
========================
ТЕКУЩИЙ ПОЛЬЗОВАТЕЛЬ
========================

Имя: {user_name}
ID: {user_id}

Это история именно текущего пользователя.
Не смешивай её с другими людьми.

========================
ПРЕДЫДУЩАЯ ИСТОРИЯ
========================
"""

    if history:

        for item in history:

            role = item.get(
                "role",
                "user"
            )

            content = item.get(
                "content",
                ""
            )

            if role == "user":

                personal_context += (
                    f"\nПользователь: {content}"
                )

            elif role == "assistant":

                personal_context += (
                    f"\nБот: {content}"
                )

    else:

        personal_context += (
            "\nЭто первое сообщение пользователя."
        )

    # =========================
    # WIKI
    # =========================

    wiki_context = ""

    if looks_like_tank_question(
        user_message
    ):

        wiki_result = search_lesta_wiki(
            user_message
        )

        if wiki_result:

            wiki_context = f"""
========================
ИНФОРМАЦИЯ ИЗ ЛЕСТА WIKI
========================

Это данные, полученные из Леста Wiki.

Используй их как основной источник
для ответа о танке.

Не меняй цифры.
Не придумывай отсутствующие характеристики.

{wiki_result}
"""

        else:

            wiki_context = """
========================
ЛЕСТА WIKI
========================

Подходящую информацию получить не удалось.

Не придумывай точные характеристики танка.
Если точных данных нет — так и скажи.
"""

    # =========================
    # СООБЩЕНИЯ ДЛЯ GROQ
    # =========================

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT
        },
        {
            "role": "system",
            "content": personal_context
        }
    ]

    if wiki_context:

        messages.append({
            "role": "system",
            "content": wiki_context
        })

    messages.append({
        "role": "user",
        "content": user_message
    })

    # =========================
    # ЗАПРОС GROQ
    # =========================

    completion = client.chat.completions.create(
        model="openai/gpt-oss-120b",
        messages=messages,
        max_tokens=500
    )

    return (
        completion
        .choices[0]
        .message
        .content
        .strip()
    )


