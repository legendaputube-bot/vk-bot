def clean_wiki_text(
    text: str
) -> str:

    if not text:
        return ""

    # HTML
    text = re.sub(
        r"<[^>]+>",
        " ",
        text
    )

    # Вики-шаблоны
    text = re.sub(
        r"\{\{.*?\}\}",
        " ",
        text,
        flags=re.DOTALL
    )

    # [[Название|Текст]]
    text = re.sub(
        r"\[\[([^|\]]+)\|([^\]]+)\]\]",
        r"\2",
        text
    )

    # [[Название]]
    text = re.sub(
        r"\[\[([^\]]+)\]\]",
        r"\1",
        text
    )

    # Ссылки
    text = re.sub(
        r"\[https?://[^\s\]]+\s*([^\]]*)\]",
        r"\1",
        text
    )

    # Жирный/курсив
    text = text.replace(
        "'''",
        ""
    )

    text = text.replace(
        "''",
        ""
    )

    # Пробелы
    text = re.sub(
        r"[ \t]+",
        " ",
        text
    )

    # Пустые строки
    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )

    return text.strip()


def search_lesta_wiki(
    query: str
) -> str:

    """
    Ищет подходящую статью в Леста Wiki
    и получает её текст.
    """

    try:

        print(
            f"Wiki: поиск по запросу: {query}",
            flush=True
        )

        # =========================
        # ПОИСК СТАТЬИ
        # =========================

        search_params = {
            "action": "query",
            "list": "search",
            "srsearch": query,
            "format": "json",
            "formatversion": "2",
            "srlimit": 5
        }

        response = requests.get(
            WIKI_API_URL,
            params=search_params,
            timeout=15,
            headers={
                "User-Agent": "TanksBlitzVKBot/1.0"
            }
        )

        response.raise_for_status()

        data = response.json()

        results = (
            data
            .get("query", {})
            .get("search", [])
        )

        if not results:

            print(
                "Wiki: ничего не найдено",
                flush=True
            )

            return ""

        # =========================
        # ВЫБИРАЕМ СТРАНИЦУ
        # =========================

        page = results[0]

        page_id = page.get(
            "pageid"
        )

        page_title = page.get(
            "title",
            ""
        )

        if not page_id:

            return ""

        print(
            f"Wiki: найдена статья: {page_title}",
            flush=True
        )

        # =========================
        # ПОЛУЧАЕМ ТЕКСТ
        # =========================

        page_params = {
            "action": "query",
            "prop": "extracts",
            "pageids": page_id,
            "explaintext": "1",
            "exsectionformat": "plain",
            "format": "json",
            "formatversion": "2"
        }

        page_response = requests.get(
            WIKI_API_URL,
            params=page_params,
            timeout=15,
            headers={
                "User-Agent": "TanksBlitzVKBot/1.0"
            }
        )

        page_response.raise_for_status()

        page_data = page_response.json()

        pages = (
            page_data
            .get("query", {})
            .get("pages", [])
        )

        if not pages:

            return ""

        extract = pages[0].get(
            "extract",
            ""
        )

        extract = clean_wiki_text(
            extract
        )

        if not extract:

            return ""

        # Ограничение размера
        if len(extract) > MAX_WIKI_TEXT:

            extract = extract[
                :MAX_WIKI_TEXT
            ]

            extract += (
                "\n\n[Статья сокращена.]"
            )

        wiki_url = (
            "https://wiki.lesta.ru/ru/"
            + requests.utils.quote(
                page_title.replace(
                    " ",
                    "_"
                ),
                safe="_-()"
            )
        )

        return (
            f"Название статьи: {page_title}\n"
            f"Источник: {wiki_url}\n\n"
            f"{extract}"
        )

    except Exception as e:

        print(
            "Ошибка Леста Wiki:",
            e,
            flush=True
        )

        return ""


