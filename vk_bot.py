@app.route(
    "/callback",
    methods=["POST"]
)
def callback():

    try:

        data = request.get_json(
            force=True
        )

    except Exception:

        return "bad request", 400

    # =========================
    # SECRET
    # =========================

    if (
        VK_GROUP_SECRET
        and data.get("secret") != VK_GROUP_SECRET
    ):

        print(
            "Неверный secret",
            flush=True
        )

        return "invalid secret", 403

    event_type = data.get(
        "type"
    )

    # =========================
    # CONFIRMATION
    # =========================

    if event_type == "confirmation":

        return VK_CONFIRMATION_CODE

    # =========================
    # НОВОЕ СООБЩЕНИЕ
    # =========================

    if event_type == "message_new":

        try:

            message = data[
                "object"
            ][
                "message"
            ]

            # Кто написал
            user_id = message[
                "from_id"
            ]

            # Куда отвечать
            peer_id = message[
                "peer_id"
            ]

            text = message.get(
                "text",
                ""
            ).strip()

            # Пустые сообщения
            if not text:

                return "ok"

            # Игнорируем сообщения
            # от сообществ
            if user_id <= 0:

                return "ok"

            print(
                f"Новое сообщение от {user_id}: {text}",
                flush=True
            )

            # =========================
            # ПОЛЬЗОВАТЕЛЬ
            # =========================

            user_data = get_user_data(
                user_id
            )

            user_name = user_data.get(
                "name",
                "Участник"
            )

            print(
                f"Пользователь: {user_name}",
                flush=True
            )

            # =========================
            # СОХРАНЯЕМ ВОПРОС
            # =========================

            add_to_history(
                user_id,
                "user",
                text
            )

            # =========================
            # GROQ + WIKI
            # =========================

            try:

                reply = ask_groq(
                    user_id,
                    text
                )

            except Exception as e:

                print(
                    "Ошибка Groq/Wiki:",
                    e,
                    flush=True
                )

                reply = (
                    "Что-то я сейчас подвис 😅 "
                    "Попробуй написать ещё раз."
                )

            # =========================
            # СОХРАНЯЕМ ОТВЕТ
            # =========================

            add_to_history(
                user_id,
                "assistant",
                reply
            )

            # =========================
            # ОТВЕЧАЕМ В ТО ЖЕ МЕСТО
            # =========================

            send_vk_message(
                peer_id,
                reply
            )

        except Exception as e:

            print(
                "Ошибка обработки сообщения:",
                e,
                flush=True
            )

        return "ok"

    return "ok"


