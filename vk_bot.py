users_memory = {}

memory_lock = threading.Lock()


def load_memory():

    global users_memory

    try:

        if os.path.exists(MEMORY_FILE):

            with open(
                MEMORY_FILE,
                "r",
                encoding="utf-8"
            ) as file:

                users_memory = json.load(file)

            print(
                f"Память загружена. Пользователей: {len(users_memory)}",
                flush=True
            )

        else:

            users_memory = {}

    except Exception as e:

        print(
            "Ошибка загрузки памяти:",
            e,
            flush=True
        )

        users_memory = {}


def save_memory():

    try:

        with open(
            MEMORY_FILE,
            "w",
            encoding="utf-8"
        ) as file:

            json.dump(
                users_memory,
                file,
                ensure_ascii=False,
                indent=2
            )

    except Exception as e:

        print(
            "Ошибка сохранения памяти:",
            e,
            flush=True
        )


def get_user_name(
    user_id: int
) -> str:

    try:

        params = {
            "access_token": VK_TOKEN,
            "v": VK_API_VERSION,
            "user_ids": user_id,
            "fields": "first_name,last_name"
        }

        response = requests.get(
            "https://api.vk.com/method/users.get",
            params=params,
            timeout=10
        )

        result = response.json()

        if (
            "response" in result
            and result["response"]
        ):

            user = result["response"][0]

            first_name = user.get(
                "first_name",
                ""
            )

            last_name = user.get(
                "last_name",
                ""
            )

            full_name = (
                f"{first_name} {last_name}"
                .strip()
            )

            if full_name:
                return full_name

    except Exception as e:

        print(
            "Ошибка получения имени:",
            e,
            flush=True
        )

    return "Участник"


def get_user_data(
    user_id: int
):

    user_key = str(user_id)

    with memory_lock:

        if user_key in users_memory:

            return users_memory[user_key]

    user_name = get_user_name(
        user_id
    )

    with memory_lock:

        if user_key not in users_memory:

            users_memory[user_key] = {
                "name": user_name,
                "history": []
            }

            save_memory()

        return users_memory[user_key]


def add_to_history(
    user_id: int,
    role: str,
    content: str
):

    user_key = str(user_id)

    with memory_lock:

        if user_key not in users_memory:

            users_memory[user_key] = {
                "name": "Участник",
                "history": []
            }

        history = users_memory[user_key]["history"]

        history.append({
            "role": role,
            "content": content
        })

        if len(history) > MAX_HISTORY:

            users_memory[user_key]["history"] = (
                history[-MAX_HISTORY:]
            )

        save_memory()


